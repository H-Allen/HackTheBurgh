"""
export_fpga.py - turn tree.pkl into rtl/bat_tree.v and make golden test vectors.

  python export_fpga.py
Outputs:
  rtl/bat_tree.v               combinational decision tree (class id + confidence)
  golden/bins.hex              FFT magnitude stream: one 32-bit word per bin = (bin<<16)|mag
  golden/expected_events.txt   frame class conf dur f_start f_end f_peak f_min f_max bw sweep
  golden/classes.txt           class id -> name, risk group
  golden/tree.hex              node table for the programmable tree (tree_walker.v), loaded at run time
  golden/audio.wav             same audio as a 256 kHz mono wav (demo input for board/run_bat.py)
  golden/audio.hex             int16 audio stream (one 16-bit word per sample) for the full-chain test
  golden/bins_fixed.hex        same as bins.hex but from the RTL fixed-point FFT model (fft_model.py)
  golden/expected_events_fixedfft.txt   events from the fixed-point FFT (bit-exact target for bat_top)
"""
import os, pickle, wave
import numpy as np
from bat_model import fft_mags, frame_stats, detect, FEATURES
from fft_model import fft_mags_fixed
from synth_bats import make_recording, CLASSES, RISK

os.makedirs("rtl", exist_ok=True); os.makedirs("golden", exist_ok=True)
m = pickle.load(open("tree.pkl", "rb"))
dt = m["tree"]; T = dt.tree_
assert len(CLASSES) <= 16

def leaf(node):
    v = T.value[node][0]
    v = v / v.sum()
    return int(dt.classes_[int(np.argmax(v))]), int(np.floor(v.max() * 255))

def predict_int(f):
    n = 0
    while T.children_left[n] != -1:
        thr = int(np.floor(T.threshold[n]))       # x <= t.5  <=>  x <= floor(t)
        n = T.children_left[n] if f[T.feature[n]] <= thr else T.children_right[n]
    return leaf(n)

# ---------------- Verilog ----------------
lines = []
def emit(n, ind):
    p = "    " * ind
    if T.children_left[n] == -1:
        c, conf = leaf(n)
        lines.append(f"{p}begin cls = 4'd{c}; conf = 8'd{conf}; end  // {CLASSES[c]}")
        return
    thr = int(np.floor(T.threshold[n]))
    fname = FEATURES[T.feature[n]]
    port = fname if fname.startswith("f_") else "f_" + fname
    lines.append(f"{p}if ({port} <= 8'd{thr})")
    emit(T.children_left[n], ind + 1)
    lines.append(f"{p}else")
    emit(T.children_right[n], ind + 1)

emit(0, 2)
cls_comment = "\n".join(f"//   {i:2d} {c:7s} {RISK.get(c, 'other_bat')}" for i, c in enumerate(CLASSES))
v = f"""// bat_tree.v - AUTO-GENERATED by export_fpga.py from tree.pkl. Do not edit.
// depth {dt.get_depth()}, {dt.get_n_leaves()} leaves. Class ids:
{cls_comment}
`default_nettype none
module bat_tree (
    input  wire [7:0] f_dur, f_start, f_end, f_peak, f_min, f_max, f_bw, f_sweep,
    output reg  [3:0] cls,
    output reg  [7:0] conf
);
    always @* begin
        cls = 4'd0; conf = 8'd0;
{chr(10).join(lines)}
    end
endmodule
`default_nettype wire
"""
open("rtl/bat_tree.v", "w").write(v)

# ---------------- programmable tree table (tree_walker.v) ----------------
def node_word(n):
    if T.children_left[n] == -1:
        c, conf = leaf(n)
        return (1 << 31) | (c << 8) | conf
    thr = int(np.floor(T.threshold[n]))
    assert 0 <= thr <= 255 and T.node_count <= 512
    return (int(T.feature[n]) << 28) | (thr << 20) | (int(T.children_right[n]) << 9) | int(T.children_left[n])

TABLE = [node_word(n) for n in range(T.node_count)]
TABLE += [(1 << 31) | (15 << 8)] * (512 - len(TABLE))      # unused slots: invalid-class leaves


def predict_table(f, table=TABLE):
    """Python model of tree_walker.v."""
    n = 0
    while not table[n] >> 31:
        w = table[n]
        n = (w & 0x1ff) if f[(w >> 28) & 7] <= ((w >> 20) & 0xff) else ((w >> 9) & 0x1ff)
    return (table[n] >> 8) & 0xf, table[n] & 0xff

with open("golden/tree.hex", "w") as f:
    f.write("".join(f"{w:08x}\n" for w in TABLE))
_rng = np.random.default_rng(7)
_rand = _rng.integers(0, 256, (20000, 8))
assert all(predict_table(f) == predict_int(f) for f in _rand), "tree table != generated tree"

# ---------------- golden vectors ----------------
rng = np.random.default_rng(123)          # fresh recordings, not in training set
seq = ["MYODAU", "EPTSER", "PIPPIP", "NOISE", "MYOMYS", "RHIHIP", "NYCNOC", "PLEAUR"]
x = np.concatenate([make_recording(rng, c)[0] for c in seq])
mags = fft_mags(x)
E, pk = frame_stats(mags)
events = detect(E, pk)

with open("golden/bins.hex", "w") as f:
    for fr in mags:
        for b, mg in enumerate(fr):
            f.write(f"{(b << 16) | int(mg):08x}\n")
mismatch = 0
with open("golden/expected_events.txt", "w") as f:
    for st, en, feats in events:
        c, conf = predict_int(feats)
        if c != dt.predict(np.array([feats]))[0]:
            mismatch += 1
        f.write(f"{en} {c} {conf} " + " ".join(map(str, feats)) + "\n")
# full chain (audio -> RTL FFT): bit-exact targets from the fixed-point FFT model
with open("golden/audio.hex", "w") as f:
    for v in x.astype(np.int16).view(np.uint16):
        f.write(f"{int(v):04x}\n")
with wave.open("golden/audio.wav", "wb") as w:            # same audio as a 256 kHz demo wav
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(256000)
    w.writeframes(x.astype("<i2").tobytes())
mags_fx = fft_mags_fixed(x)
with open("golden/bins_fixed.hex", "w") as f:
    for fr in mags_fx:
        for b, mg in enumerate(fr):
            f.write(f"{(b << 16) | int(mg):08x}\n")
events_fx = detect(*frame_stats(mags_fx))
with open("golden/expected_events_fixedfft.txt", "w") as f:
    for st, en, feats in events_fx:
        c, conf = predict_int(feats)
        f.write(f"{en} {c} {conf} " + " ".join(map(str, feats)) + "\n")
with open("golden/classes.txt", "w") as f:
    for i, c in enumerate(CLASSES):
        f.write(f"{i} {c} {RISK.get(c, 'other_bat')}\n")

seg = len(x) // len(seq) // 256
print(f"bat_tree.v: depth {dt.get_depth()}, {dt.get_n_leaves()} leaves; tree.hex: {T.node_count}/512 nodes")
print(f"golden: {len(mags)} frames, {len(events)} events, int-vs-sklearn mismatches: {mismatch}")
print(f"fixed-point FFT: {len(events_fx)} events (float FFT: {len(events)}), "
      f"max |mag diff| {int(np.abs(mags_fx - mags).max())}")
for st, en, feats in events:
    c, conf = predict_int(feats)
    print(f"  frame {en:5d}  true {seq[min(st // seg, len(seq) - 1)]:7s} -> {CLASSES[c]:7s} conf {conf}")
