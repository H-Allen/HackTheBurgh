"""
gen_fft_rom.py - write rtl/fft256_rom.v (Hann window + twiddle ROMs) from fft_model.py constants.
  python gen_fft_rom.py
Case-statement ROMs: no $readmemh paths, so the same file works in Verilator and Vivado.
"""
from bat_model import HANN_Q15, N_FFT
from fft_model import TW_C, TW_S


def s18(v):
    return f"-18'sd{-v}" if v < 0 else f"18'sd{v}"


hann = "\n".join(f"            8'd{i}: q = 16'sd{int(v)};" for i, v in enumerate(HANN_Q15))
tw = "\n".join(f"            7'd{k}: begin c = {s18(int(TW_C[k]))}; s = {s18(int(TW_S[k]))}; end"
               for k in range(N_FFT // 2))
v = f"""// fft256_rom.v - AUTO-GENERATED by gen_fft_rom.py. Do not edit.
`default_nettype none
// Hann window, Q15 (same as bat_model.HANN_Q15)
module hann_rom (
    input  wire        [7:0]  addr,
    output reg  signed [15:0] q
);
    always @* begin
        case (addr)
{hann}
            default: q = 16'sd0;
        endcase
    end
endmodule

// Twiddles W_k = e^(-j 2 pi k / 256), Q16 in 18-bit signed: c = cos, s = -sin
module twiddle_rom (
    input  wire        [6:0]  addr,
    output reg  signed [17:0] c,
    output reg  signed [17:0] s
);
    always @* begin
        case (addr)
{tw}
            default: begin c = 18'sd0; s = 18'sd0; end
        endcase
    end
endmodule
`default_nettype wire
"""
open("rtl/fft256_rom.v", "w").write(v)
print("wrote rtl/fft256_rom.v")
